export function reportToMarkdown(report) {
  const lines = [];
  lines.push(`# Domain Auth Fix-it Report`);
  lines.push(``);
  lines.push(`**Domain:** ${report.domain}`);
  lines.push(`**Score:** ${report.score}/100`);
  lines.push(`**Generated:** ${report.createdAt}`);
  lines.push(`**Report ID:** ${report.id}`);
  lines.push(``);
  lines.push(`> DNS health ≠ inbox guarantee. Passing SPF/DKIM/DMARC does not promise inbox placement or open rates.`);
  lines.push(``);
  lines.push(`## Top issues`);
  lines.push(``);
  for (const issue of report.topIssues) {
    lines.push(`- **[${issue.severity}] ${issue.title}** — ${issue.impact}`);
  }
  lines.push(``);
  lines.push(`## Full Fix-it checklist`);
  lines.push(``);
  for (const issue of report.fullIssues) {
    lines.push(`### ${issue.title}`);
    lines.push(``);
    lines.push(`- **Category:** ${issue.category}`);
    lines.push(`- **Severity:** ${issue.severity}`);
    lines.push(`- **Impact:** ${issue.impact}`);
    if (issue.suggestedRecord) {
      lines.push(`- **Suggested DNS record:**`);
      lines.push(``);
      lines.push("```");
      lines.push(issue.suggestedRecord);
      lines.push("```");
    }
    if (issue.whereToPaste) {
      lines.push(`- **Where to paste:** ${issue.whereToPaste}`);
    }
    if (issue.details) {
      lines.push(`- **Details:** ${issue.details}`);
    }
    lines.push(``);
  }
  lines.push(`## Raw findings (summary)`);
  lines.push(``);
  lines.push(`- MX: ${report.findings.mx.present ? report.findings.mx.records.join(", ") : "missing"}`);
  lines.push(`- SPF: ${report.findings.spf.present ? report.findings.spf.record : "missing"} (lookups ≈ ${report.findings.spf.lookupCountApprox}/10)`);
  lines.push(
    `- DKIM: ${
      report.findings.dkim.selectorsFound.length
        ? report.findings.dkim.selectorsFound.map((s) => s.selector).join(", ")
        : "none found"
    }`
  );
  lines.push(`- DMARC: ${report.findings.dmarc.present ? report.findings.dmarc.record : "missing"}`);
  lines.push(`- BIMI: ${report.findings.bimi.present ? report.findings.bimi.record : "missing"}`);
  lines.push(``);
  lines.push(`---`);
  lines.push(`Generated by Domain Auth Fix-it. DNS health ≠ inbox guarantee.`);
  return lines.join("\n");
}

export function newReportId() {
  if (typeof crypto !== "undefined" && crypto.randomUUID) return crypto.randomUUID();
  return `r_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 10)}`;
}

export function buildReport({ domain, selector, findings, score, topIssues, fullIssues, paid = false, id, createdAt }) {
  return {
    id: id || newReportId(),
    domain,
    selector: selector || undefined,
    createdAt: createdAt || new Date().toISOString(),
    paid,
    score,
    topIssues,
    fullIssues,
    findings,
  };
}
